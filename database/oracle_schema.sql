    AVAILABILITY_STATUS VARCHAR2(20) DEFAULT 'Available' CHECK (AVAILABILITY_STATUS IN ('Available', 'Busy', 'On-Leave')),
    CREATED_AT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
